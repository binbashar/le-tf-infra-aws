"""Render an Infracost config file for a set of OpenTofu layers.

Replaces the hand-maintained ``infracost.yml``: every project is a layer directory plus the
three var files Leverage auto-loads for it, so the list is derived from the tree and cannot
drift from it.
"""

from __future__ import annotations

import json
import posixpath
from pathlib import Path
from typing import Iterable

# Infracost CLI v0.10 reads config version 0.1 (flat ``terraform_var_files``); CLI v2 reads
# version 0.3 (nested ``terraform: var_files``). Both are relative to the project path.
SCHEMAS = ("0.1", "0.3")


def var_files(layer: str) -> list[str]:
    """The var files Leverage loads for ``layer``, relative to the layer directory."""
    account = layer.split("/", 1)[0]
    targets = (
        "config/common.tfvars",
        f"{account}/config/account.tfvars",
        f"{account}/config/backend.tfvars",
    )
    return [posixpath.relpath(target, layer) for target in targets]


def _quote(value: str) -> str:
    # A JSON string is a valid YAML double-quoted scalar, and layer paths may contain
    # spaces, so quote every value rather than reason about which ones need it.
    return json.dumps(value)


def render(layers: Iterable[str], *, schema: str = "0.1") -> str:
    if schema not in SCHEMAS:
        raise ValueError(f"unsupported Infracost config schema {schema!r}; use one of {SCHEMAS}")
    ordered = sorted(set(layers))
    lines = [
        "# Generated by @bin/scripts/infracost_ci -- do not edit.",
        f"version: {_quote(schema)}",
    ]
    if not ordered:
        lines.append("projects: []")
        return "\n".join(lines) + "\n"
    lines.append("projects:")
    for layer in ordered:
        lines.append(f"  - path: {_quote(layer)}")
        # Without an explicit name Infracost derives one, and a layer present on only one
        # side of the diff came out as "main" instead of its path.
        lines.append(f"    name: {_quote(layer)}")
        if schema == "0.1":
            lines.append("    terraform_var_files:")
            indent = "      "
        else:
            lines.extend(["    terraform:", "      var_files:"])
            indent = "        "
        lines.extend(f"{indent}- {_quote(path)}" for path in var_files(layer))
    return "\n".join(lines) + "\n"


def write(path: Path, layers: Iterable[str], *, schema: str = "0.1") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(layers, schema=schema), encoding="utf-8")
